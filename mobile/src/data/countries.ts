/** ISO2 → 🇺🇸 style flag emoji via regional indicator symbols. */
function flagEmoji(iso2: string): string {
  return String.fromCodePoint(
    ...[...iso2.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  )
}

const US_GNI = 76370

/** GNI relative to the US, clamped to stay playable. */
function multiplierFor(gni: number): number {
  return Math.min(1.35, Math.max(0.04, gni / US_GNI))
}

export const COUNTRIES: Country[] = ROWS.map(([code, name, gni]) => ({
  code,
  name,
  flag: flagEmoji(code),
  multiplier: Math.round(multiplierFor(gni) * 100) / 100,
})).sort((a, b) => a.name.localeCompare(b.name))

export function getCountry(code: string | null): Country | null {
  return code ? (COUNTRIES.find((c) => c.code === code) ?? null) : null
}

/** Country-adjusted yearly salary for a job. */
export function countrySalary(baseSalary: number, code: string | null): number {
  const multiplier = getCountry(code)?.multiplier ?? 1
  return Math.max(500, Math.round((baseSalary * multiplier) / 100) * 100)
}

/** Generic country scaling for costs (tuition, expenses, etc.). */
export function scaleByCountry(amount: number, code: string | null): number {
  const multiplier = getCountry(code)?.multiplier ?? 1
  return Math.round(amount * multiplier)
}
